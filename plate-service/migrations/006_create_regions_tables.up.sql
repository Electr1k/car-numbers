CREATE TABLE IF NOT EXISTS regions (
    id SMALLINT PRIMARY KEY,
    name VARCHAR(64) NOT NULL,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT regions_name_uk UNIQUE (name)
);

comment on column regions.id is 'Код субъекта РФ';
comment on column regions.name is 'Название региона';

CREATE TABLE IF NOT EXISTS region_codes (
    code VARCHAR(3) PRIMARY KEY,
    region_id SMALLINT NOT NULL REFERENCES regions(id),
    created_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS idx_region_codes_region_id ON region_codes (region_id);

comment on column region_codes.code is 'Код региона';
comment on column region_codes.region_id is 'Идентификатор региона';

